# Builds src/_cezi_table.txt, the radical and stroke table that 测字 in the study reads, from Unicode's Unihan
# database: the 6,763 characters of GB 2312 (kGB0), each with its Kangxi radical (kRSUnicode, the first value) and
# its total stroke count (kTotalStrokes, the first value, the one for simplified Chinese).
# Unihan.zip comes from https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip and is not kept in the project.
# Usage: python3 tools/cezi_table.py <folder with the unzipped Unihan_*.txt files>
import os, sys
src = sys.argv[1]
fields = {}
for name in ('Unihan_OtherMappings.txt', 'Unihan_IRGSources.txt'):
    for line in open(os.path.join(src, name), encoding='utf-8'):
        if not line.startswith('U+'): continue
        cp, key, value = line.rstrip('\n').split('\t', 2)
        if key in ('kGB0', 'kRSUnicode', 'kTotalStrokes'): fields.setdefault(int(cp[2:], 16), {})[key] = value
chars, rad, strokes = [], [], []
for cp in sorted(c for c, f in fields.items() if 'kGB0' in f):
    f = fields[cp]
    rs = f['kRSUnicode'].split()[0]                       # e.g. 61.8, or 149'.6 when the radical takes its simplified form
    n = int(rs.split('.')[0].rstrip("'"))
    simplified = "'" in rs.split('.')[0]
    s = int(f['kTotalStrokes'].split()[0])
    assert 1 <= n <= 214 and 1 <= s <= 40, (hex(cp), rs, s)
    chars.append(chr(cp)); rad.append(chr(0x100 + n + (256 if simplified else 0))); strokes.append(chr(0x30 + s))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', '_cezi_table.txt')
with open(out, 'w', encoding='utf-8') as w:
    w.write('/* ---------- 测字: radical and stroke count for the 6,763 characters of GB 2312 (generated by tools/cezi_table.py) ---------- */\n')
    w.write('/*\n * From the Unihan database, © Unicode, Inc., under the Unicode License v3 (see LICENSE-UNICODE.txt).\n')
    w.write(" * CEZI_RAD: one character per entry, code 0x100 + the Kangxi radical number, + 0x100 more when the radical takes its\n")
    w.write(' * simplified form (讠 for 言, 钅 for 金…). CEZI_STROKES: code 0x30 + the stroke count.\n */\n')
    w.write(f"const CEZI_CHARS = '{''.join(chars)}';\n")
    w.write(f"const CEZI_RAD = '{''.join(rad)}';\n")
    w.write(f"const CEZI_STROKES = '{''.join(strokes)}';\n")
print(len(chars), 'characters ->', os.path.relpath(out))
